import { useState, useEffect } from 'react';
import { motion } from 'framer-motion';
import { FileBarChart, Users, TrendingUp, AlertTriangle, BookOpen, Sparkles, BrainCircuit } from 'lucide-react';
import { useAuth } from '../../hooks/useAuth';
import { classApi, type ClassInfo, type ClassInsights } from '../../services/api';

export default function Reports() {
  const { user } = useAuth();
  const [classes, setClasses] = useState<ClassInfo[]>([]);
  const [selectedClass, setSelectedClass] = useState<number | null>(null);
  const [insights, setInsights] = useState<ClassInsights | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    if (!user) return;
    classApi.getAll(user.id).then(res => {
      setClasses(res);
      if (res.length > 0) setSelectedClass(res[0].id);
    }).catch(console.error);
  }, [user]);

  useEffect(() => {
    if (!selectedClass) return;
    setLoading(true);
    classApi.getInsights(selectedClass)
      .then(setInsights)
      .catch(console.error)
      .finally(() => setLoading(false));
  }, [selectedClass]);

  const riskColors: Record<string, string> = {
    'High': 'var(--risk-high)',
    'Medium': 'var(--risk-medium)',
    'Low': 'var(--risk-low)'
  };

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: 24, paddingBottom: 32, maxWidth: 1200, margin: '0 auto', height: '100%' }}>
      
      {/* Header */}
      <header className="glass-card" style={{ padding: '32px', borderRadius: 24, display: 'flex', justifyContent: 'space-between', alignItems: 'center', background: 'linear-gradient(135deg, var(--surface), var(--surface-2))' }}>
        <div>
          <div style={{ display: 'inline-flex', alignItems: 'center', gap: 8, color: 'var(--accent)', background: 'var(--accent-soft)', padding: '6px 14px', borderRadius: 16, fontSize: '0.85rem', fontWeight: 700, marginBottom: 16, boxShadow: '0 4px 12px rgba(0,0,0,0.05)' }}>
            <FileBarChart size={16} /> Advanced Analytics
          </div>
          <h2 style={{ fontFamily: 'var(--font-heading)', fontSize: '2.2rem', fontWeight: 800, margin: 0, color: 'var(--text)' }}>Class Reports</h2>
          <p style={{ color: 'var(--text-muted)', margin: '8px 0 0', fontSize: '1.05rem', maxWidth: 600 }}>
            Comprehensive performance and behavioural analytics generated by the AI engine.
          </p>
        </div>
        
        <div style={{ display: 'flex', gap: 16, alignItems: 'center' }}>
          <select 
            value={selectedClass || ''} 
            onChange={e => setSelectedClass(Number(e.target.value))} 
            className="input premium-input" 
            style={{ width: 220, fontSize: '1.05rem', fontWeight: 700 }}
          >
            {classes.map(c => <option key={c.id} value={c.id}>{c.name}</option>)}
          </select>
        </div>
      </header>

      {loading ? (
        <div style={{ display: 'flex', gap: 24 }}>
          <div className="skeleton" style={{ flex: 1, height: 150, borderRadius: 24 }} />
          <div className="skeleton" style={{ flex: 1, height: 150, borderRadius: 24 }} />
          <div className="skeleton" style={{ flex: 1, height: 150, borderRadius: 24 }} />
        </div>
      ) : !insights ? (
        <div className="glass-card" style={{ padding: 48, textAlign: 'center', borderRadius: 24 }}>
          <FileBarChart size={48} style={{ color: 'var(--text-muted)', margin: '0 auto 16px', opacity: 0.5 }} />
          <h3 style={{ fontSize: '1.4rem', fontWeight: 700, marginBottom: 8, color: 'var(--text)' }}>No Data Available</h3>
          <p style={{ color: 'var(--text-muted)', fontSize: '1.05rem' }}>There is not enough prediction data to generate reports for this class.</p>
        </div>
      ) : (
        <>
          {/* Quick Stats Grid */}
          <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(250px, 1fr))', gap: 24 }}>
            <motion.div initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} className="glass-card" style={{ padding: 24, borderRadius: 24, border: '1px solid var(--border)' }}>
              <div style={{ display: 'flex', alignItems: 'center', gap: 12, marginBottom: 16 }}>
                <div style={{ width: 48, height: 48, borderRadius: 16, background: 'var(--surface-2)', display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
                  <Users size={24} color="var(--accent)" />
                </div>
                <div style={{ fontSize: '1rem', fontWeight: 700, color: 'var(--text-muted)' }}>Enrolled Students</div>
              </div>
              <div style={{ fontSize: '2.5rem', fontWeight: 800, color: 'var(--text)' }}>{insights.studentCount}</div>
            </motion.div>

            <motion.div initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.1 }} className="glass-card" style={{ padding: 24, borderRadius: 24, border: '1px solid var(--border)' }}>
              <div style={{ display: 'flex', alignItems: 'center', gap: 12, marginBottom: 16 }}>
                <div style={{ width: 48, height: 48, borderRadius: 16, background: 'var(--risk-low-soft)', display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
                  <TrendingUp size={24} color="var(--risk-low)" />
                </div>
                <div style={{ fontSize: '1rem', fontWeight: 700, color: 'var(--text-muted)' }}>Average Prediction</div>
              </div>
              <div style={{ fontSize: '2.5rem', fontWeight: 800, color: 'var(--risk-low)' }}>{insights.averageScore.toFixed(1)}%</div>
            </motion.div>

            <motion.div initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.2 }} className="glass-card" style={{ padding: 24, borderRadius: 24, border: '1px solid var(--border)' }}>
              <div style={{ display: 'flex', alignItems: 'center', gap: 12, marginBottom: 16 }}>
                <div style={{ width: 48, height: 48, borderRadius: 16, background: 'var(--risk-high-soft)', display: 'flex', alignItems: 'center', justifyContent: 'center' }}>
                  <AlertTriangle size={24} color="var(--risk-high)" />
                </div>
                <div style={{ fontSize: '1rem', fontWeight: 700, color: 'var(--text-muted)' }}>High Risk Students</div>
              </div>
              <div style={{ fontSize: '2.5rem', fontWeight: 800, color: 'var(--risk-high)' }}>
                {insights.riskDistribution['High'] || 0}
              </div>
            </motion.div>
          </div>

          <div style={{ display: 'grid', gridTemplateColumns: '2fr 1fr', gap: 24, marginTop: 8 }}>
            
            {/* Predicted vs Actual Chart */}
            <motion.div initial={{ opacity: 0, scale: 0.98 }} animate={{ opacity: 1, scale: 1 }} className="glass-card" style={{ padding: 32, borderRadius: 24, border: '1px solid var(--border)' }}>
              <h3 style={{ margin: '0 0 24px 0', fontSize: '1.4rem', fontWeight: 800, color: 'var(--text)', display: 'flex', alignItems: 'center', gap: 12 }}>
                <BrainCircuit size={22} color="var(--accent)" />
                Prediction Accuracy vs Actual
              </h3>
              
              <div style={{ display: 'flex', flexDirection: 'column', gap: 16, maxHeight: 400, overflowY: 'auto', paddingRight: 12 }}>
                {insights.predictedVsActual.map((data, i) => (
                  <div key={i} style={{ display: 'grid', gridTemplateColumns: '150px 1fr', gap: 16, alignItems: 'center', background: 'var(--surface-2)', padding: '16px 20px', borderRadius: 16 }}>
                    <div style={{ fontWeight: 700, fontSize: '0.95rem', color: 'var(--text)' }}>{data.name}</div>
                    
                    <div style={{ display: 'flex', flexDirection: 'column', gap: 8, flex: 1 }}>
                      {/* Predicted Bar */}
                      <div style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
                        <div style={{ width: 60, fontSize: '0.75rem', fontWeight: 700, color: 'var(--text-muted)' }}>Predicted</div>
                        <div style={{ flex: 1, height: 8, background: 'var(--surface)', borderRadius: 4, overflow: 'hidden' }}>
                          <motion.div initial={{ width: 0 }} animate={{ width: `${data.predicted_score}%` }} style={{ height: '100%', background: 'var(--accent)', borderRadius: 4 }} />
                        </div>
                        <div style={{ width: 40, textAlign: 'right', fontWeight: 700, fontSize: '0.85rem' }}>{Math.round(data.predicted_score)}</div>
                      </div>
                      
                      {/* Actual Bar */}
                      <div style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
                        <div style={{ width: 60, fontSize: '0.75rem', fontWeight: 700, color: 'var(--text-muted)' }}>Actual</div>
                        <div style={{ flex: 1, height: 8, background: 'var(--surface)', borderRadius: 4, overflow: 'hidden' }}>
                          <motion.div initial={{ width: 0 }} animate={{ width: `${data.actual_score}%` }} style={{ height: '100%', background: 'var(--risk-low)', borderRadius: 4 }} />
                        </div>
                        <div style={{ width: 40, textAlign: 'right', fontWeight: 700, fontSize: '0.85rem' }}>{Math.round(data.actual_score)}</div>
                      </div>
                    </div>
                  </div>
                ))}
                {insights.predictedVsActual.length === 0 && (
                  <div style={{ textAlign: 'center', padding: 24, color: 'var(--text-muted)' }}>No exam marks recorded yet to compare with predictions.</div>
                )}
              </div>
            </motion.div>

            {/* Feature Importance & Risk Distribution */}
            <div style={{ display: 'flex', flexDirection: 'column', gap: 24 }}>
              
              <motion.div initial={{ opacity: 0, x: 20 }} animate={{ opacity: 1, x: 0 }} className="glass-card" style={{ padding: 32, borderRadius: 24, border: '1px solid var(--border)', flex: 1 }}>
                <h3 style={{ margin: '0 0 24px 0', fontSize: '1.2rem', fontWeight: 800, color: 'var(--text)', display: 'flex', alignItems: 'center', gap: 8 }}>
                  <Sparkles size={18} color="var(--accent)" /> AI Key Drivers
                </h3>
                
                <div style={{ display: 'flex', flexDirection: 'column', gap: 16 }}>
                  {insights.featureImportance.map((feat, i) => (
                    <div key={i} style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                      <div style={{ fontSize: '0.9rem', fontWeight: 600, color: 'var(--text)' }}>
                        {feat.name.replace(/_/g, ' ')}
                      </div>
                      <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
                        <div style={{ fontSize: '0.85rem', fontWeight: 800, color: feat.direction === 'positive' ? 'var(--risk-low)' : 'var(--risk-high)' }}>
                          {(feat.importance * 100).toFixed(0)}%
                        </div>
                        <TrendingUp size={16} color={feat.direction === 'positive' ? 'var(--risk-low)' : 'var(--risk-high)'} style={{ transform: feat.direction === 'positive' ? 'none' : 'rotate(180deg)' }} />
                      </div>
                    </div>
                  ))}
                </div>
              </motion.div>

              <motion.div initial={{ opacity: 0, x: 20 }} animate={{ opacity: 1, x: 0 }} transition={{ delay: 0.1 }} className="glass-card" style={{ padding: 32, borderRadius: 24, border: '1px solid var(--border)' }}>
                <h3 style={{ margin: '0 0 24px 0', fontSize: '1.2rem', fontWeight: 800, color: 'var(--text)' }}>Risk Distribution</h3>
                <div style={{ display: 'flex', flexDirection: 'column', gap: 12 }}>
                  {Object.entries(insights.riskDistribution).map(([level, count]) => (
                    <div key={level} style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
                      <div style={{ width: 80, fontSize: '0.9rem', fontWeight: 700, color: riskColors[level] }}>{level}</div>
                      <div style={{ flex: 1, height: 8, background: 'var(--surface)', borderRadius: 4, overflow: 'hidden' }}>
                        <div style={{ width: `${(count / insights.studentCount) * 100}%`, height: '100%', background: riskColors[level], borderRadius: 4 }} />
                      </div>
                      <div style={{ width: 24, textAlign: 'right', fontWeight: 800, fontSize: '0.9rem', color: 'var(--text)' }}>{count}</div>
                    </div>
                  ))}
                </div>
              </motion.div>

            </div>
          </div>
        </>
      )}
    </div>
  );
}
